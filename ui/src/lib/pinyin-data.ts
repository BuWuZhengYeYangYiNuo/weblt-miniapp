/**
 * 查询候选汉字
 * @param pinyin 完整拼音（不带声调）
 * @returns 候选汉字数组
 */
export function lookupPinyin(pinyin: string): string[] {
  if (!pinyin) return []
  return PINYIN_INDEX[pinyin.toLowerCase()] || []
}

/**
 * 拼音首字母索引（备用 fallback）：输入单个字母返回所有该首字母的字
 */
export const FIRST_LETTER_INDEX: Record<string, string[]> = (() => {
  const map: Record<string, string[]> = {}
  for (const py in PINYIN_INDEX) {
    const first = py[0]
    if (!map[first]) map[first] = []
    for (const ch of PINYIN_INDEX[py]) {
      if (map[first].indexOf(ch) === -1) {
        map[first].push(ch)
      }
    }
  }
  return map
})()